def build_docs(refs):
  group_size = 3
  merged = []
  for start in range(0, len(refs), group_size):
    block = "\n".join([f"Fact {start + j}: {refs[start + j]}" for j in range(min(group_size, len(refs) - start))])
    merged.append(Document(page_content=block,metadata={"start_id": start, "group_size": group_size}))
  return merged

from langchain_core.documents import Document
