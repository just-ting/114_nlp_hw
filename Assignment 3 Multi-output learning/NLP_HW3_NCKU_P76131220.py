# TODO2: Construct your model
# Reference:　https://medium.com/%40parkermo_86729/using-pytorch-hugging-face-and-a-pretrained-bert-model-to-create-news-source-classifier-a-46dddbd4d919
class MultiLabelModel(torch.nn.Module):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        # Write your code here
        # Define what modules you will use in the model
        # Please use "google-bert/bert-base-uncased" model (https://huggingface.co/google-bert/bert-base-uncased)
        self.bert = BertModel.from_pretrained("google-bert/bert-base-uncased")
        # Besides the base model, you may design additional architectures by incorporating linear layers, activation functions, or other neural components.
        hidden_size = self.bert.config.hidden_size
        self.dropout = torch.nn.Dropout(0.1)
        self.regression_output = torch.nn.Linear(hidden_size, 1)
        self.classification_output = torch.nn.Linear(hidden_size, 3)

        # Remark: The use of any additional pretrained language models is not permitted.
    def forward(self, **kwargs):
        # Write your code here
        # Forward pass
        input_ids = kwargs["input_ids"]
        token_type_ids = kwargs["token_type_ids"]
        attention_mask = kwargs["attention_mask"]

        outputs = self.bert(input_ids=input_ids,
                  token_type_ids=token_type_ids,
                  attention_mask=attention_mask,
                  return_dict=True)

        cls = self.dropout(outputs.last_hidden_state[:,0,:])
        reg_output = self.regression_output(cls).squeeze(-1)
        clf_output = self.classification_output(cls)

        return {"regression": reg_output, "classification": clf_output}

# TODO3: Define your optimizer and loss function

model = MultiLabelModel().to(device)
# TODO3-1: Define your Optimizer
optimizer = torch.optim.AdamW(params=model.parameters(), lr=lr)

# TODO3-2: Define your loss functions (you should have two)
# Write your code here
reg_loss_function = torch.nn.MSELoss()
clf_loss_function = torch.nn.CrossEntropyLoss()
# scoring functions
psr = load("pearsonr")
acc = load("accuracy")

best_score = 0.0
for ep in range(epochs):
    pbar = tqdm(dl_train)
    pbar.set_description(f"Training epoch [{ep+1}/{epochs}]")
    model.train()
    # TODO4: Write the training loop
    # Write your code here
    epochs_loss = 0.0
    for batch in pbar:
      # train your model
      input_ids = batch["input_ids"].to(device)
      token_type_ids = batch["token_type_ids"].to(device)
      attention_mask = batch["attention_mask"].to(device)
      regression = batch["regression"].to(device)
      classification = batch["classification"].to(device)
      # clear gradient
      optimizer.zero_grad()
      # forward pass
      outputs = model(input_ids=input_ids, token_type_ids=token_type_ids, attention_mask=attention_mask)
      # compute loss
      reg_output = outputs["regression"]
      clf_output = outputs["classification"]
      reg_loss = reg_loss_function(reg_output, regression)
      clf_loss = clf_loss_function(clf_output, classification)
      loss = reg_loss+clf_loss
      # back-propagation
      loss.backward()
      # model optimization
      optimizer.step()

      epochs_loss += loss.item()
      pbar.set_postfix(loss=f"{loss.item():.4f}")

    pbar = tqdm(dl_validation)
    pbar.set_description(f"Validation epoch [{ep+1}/{epochs}]")
    model.eval()
    # TODO5: Write the evaluation loop
    # Write your code here
    reg_preds = []
    reg_trues = []
    clf_preds = []
    clf_trues = []
    for batch in pbar:
      input_ids = batch["input_ids"].to(device)
      token_type_ids = batch["token_type_ids"].to(device)
      attention_mask = batch["attention_mask"].to(device)
      regression = batch["regression"].to(device)
      classification = batch["classification"].to(device)
      # Evaluate your model
      with torch.no_grad():
        outputs = model(input_ids=input_ids, token_type_ids=token_type_ids, attention_mask=attention_mask)
        reg_output = outputs["regression"]
        clf_output = outputs["classification"]

        reg_preds.extend(reg_output.detach().cpu().tolist())
        reg_trues.extend(regression.detach().cpu().tolist())
        clf_pred = torch.argmax(clf_output, dim=1)
        clf_preds.extend(clf_pred.detach().cpu().tolist())
        clf_trues.extend(classification.detach().cpu().tolist())


    # Output all the evaluation scores (PearsonCorr, Accuracy)
    pearson_corr = psr.compute(predictions=reg_preds, references=reg_trues)["pearsonr"]
    accuracy = acc.compute(predictions=clf_preds, references=clf_trues)["accuracy"]
    # print(f"F1 Score: {f1.compute()}")
    print(f"Pearson: {pearson_corr: .4f}, accuracy: {accuracy: .4f}")

    if pearson_corr + accuracy > best_score:
        best_score = pearson_corr + accuracy
        import os
        os.makedirs("./saved_models", exist_ok=True)
        torch.save(model.state_dict(), f'./saved_models/best_model.ckpt')

